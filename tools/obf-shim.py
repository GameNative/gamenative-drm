#!/usr/bin/env python3
"""obf-shim.py — compile-time obfuscation of the LD_PRELOAD shim's log text.

Reads `gndrm_shim.c`, rewrites every `LOG("<fmt>", args...)` call site to decode
an XOR-encoded copy of the literal at runtime, and emits the encoded table plus
the `gndrm_str`/`gndrm_logfmt` support into the output file. The literal text is
gone from the compiled `.so` (`strings` finds the encoded bytes, not the text);
the gate and the "[gndrm-shim] " prefix are unchanged.

Deterministic: identical input yields identical output. Run by
`tools/build-shim.sh`; the source stays the readable, canonical input.
"""
import re
import sys

MAX_MSG = 512
LOG_DEF = re.compile(r"#define LOG\(\.\.\.\).*?\n[^\n]*while \(0\)\n", re.S)


def match_paren(s, i):
    d = 0
    n = len(s)
    while i < n:
        c = s[i]
        if c == '"':
            i += 1
            while i < n:
                if s[i] == '\\':
                    i += 2
                    continue
                if s[i] == '"':
                    break
                i += 1
        elif c in "([{":
            d += 1
        elif c in ")]}":
            d -= 1
            if d == 0:
                return i + 1
        i += 1
    raise ValueError("unbalanced parens")


def split_top(s):
    out, depth, i, start, n = [], 0, 0, 0, len(s)
    while i < n:
        c = s[i]
        if c == '"':
            i += 1
            while i < n:
                if s[i] == '\\':
                    i += 2
                    continue
                if s[i] == '"':
                    break
                i += 1
        elif c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == "," and depth == 0:
            out.append(s[start:i])
            start = i + 1
        i += 1
    out.append(s[start:])
    return out


def c_unescape(lit):
    """Decode a single C string literal (with surrounding quotes) to bytes."""
    assert lit[0] == '"' and lit[-1] == '"'
    body = lit[1:-1]
    out = bytearray()
    i = 0
    while i < len(body):
        c = body[i]
        if c != '\\':
            out += c.encode()
            i += 1
            continue
        i += 1
        e = body[i]
        simple = {'n': 10, 't': 9, 'r': 13, '\\': 92, '"': 34, "'": 39,
                  '0': 0, 'a': 7, 'b': 8, 'f': 12, 'v': 11}
        if e in simple:
            out.append(simple[e])
            i += 1
        elif e == 'x':
            i += 1
            j = i
            while j < len(body) and body[j] in "0123456789abcdefABCDEF":
                j += 1
            out.append(int(body[i:j], 16) & 0xFF)
            i = j
        else:
            raise ValueError(f"unsupported escape \\{e}")
    return bytes(out)


def extract_literals(arg):
    """Concatenate the decoded bytes of all C string literals in `arg`."""
    out = bytearray()
    for m in re.finditer(r'"(?:[^"\\]|\\.)*"', arg):
        out += c_unescape(m.group(0))
    return bytes(out)


def key_for(b):
    h = 0x811C9DC5
    for x in b:
        h ^= x
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h & 0xFF


def main():
    src_path, out_path = sys.argv[1], sys.argv[2]
    src = open(src_path).read()

    msgs = []        # (bytes)
    repls = []       # (start, end, replacement)

    # LOG("<fmt>", args...) → GNDRM_LOGM(id, args) / GNDRM_LOGM0(id)
    for m in re.finditer(r"(?<![A-Za-z0-9_])LOG\(", src):
        lparen = m.end() - 1
        end = match_paren(src, lparen)
        inner = src[lparen + 1:end - 1]
        args = split_top(inner)
        first = args[0].strip()
        if not first.startswith('"'):
            continue  # the macro definition, not a call site
        bytes_ = extract_literals(first)
        idx = len(msgs)
        msgs.append(bytes_)
        rest = ",".join(args[1:])
        if rest.strip():
            repl = f"GNDRM_LOGM({idx},{rest})"
        else:
            repl = f"GNDRM_LOGM0({idx})"
        repls.append((m.start(), end, repl))

    # GNDRM_OBF("literal") → gndrm_ref(id): a bare diagnostic string assigned
    # to a pointer (e.g. the `why` labels) rather than a format argument.
    for m in re.finditer(r"(?<![A-Za-z0-9_])GNDRM_OBF\(", src):
        lparen = m.end() - 1
        end = match_paren(src, lparen)
        inner = src[lparen + 1:end - 1].strip()
        if not inner.startswith('"'):
            continue  # the fallback #define, not a use
        bytes_ = extract_literals(inner)
        idx = len(msgs)
        msgs.append(bytes_)
        repls.append((m.start(), end, f"gndrm_ref({idx})"))

    repls.sort(key=lambda r: r[0])
    for start, end, repl in reversed(repls):
        src = src[:start] + repl + src[end:]

    # Build the encoded table + support block.
    lines = ["/* Generated by tools/obf-shim.py — do not edit. */"]
    for i, b in enumerate(msgs):
        key = key_for(b)
        enc = ",".join(str(x ^ ((key + j) & 0xFF)) for j, x in enumerate(b))
        lines.append(f"static const unsigned char GNDRM_E_{i}[] = {{{enc}}};")
        lines.append(f"static const unsigned short GNDRM_N_{i} = {len(b)};")
    entries = ",".join(
        f"{{GNDRM_E_{i}, GNDRM_N_{i}, {key_for(b)}}}" for i, b in enumerate(msgs)
    )
    lines += [
        "typedef struct { const unsigned char *enc; unsigned short len;"
        " unsigned char key; } gndrm_msg_t;",
        f"static const gndrm_msg_t gndrm_msgs[] = {{{entries}}};",
        "static const char *gndrm_decode(unsigned id, char *buf) {",
        "    const gndrm_msg_t *m = &gndrm_msgs[id];",
        "    unsigned i;",
        "    for (i = 0; i < m->len; i++)",
        "        buf[i] = (char)(m->enc[i] ^ (unsigned char)(m->key + i));",
        "    buf[m->len] = 0;",
        "    return buf;",
        "}",
        # Two distinct buffers: a message and a `why`-style reference can be
        # live at once (the LOG site decodes its own format while `why` still
        # points at its decode), so sharing one buffer would clobber.
        f"static const char *gndrm_str(unsigned id) {{",
        f"    static _Thread_local char buf[{MAX_MSG}];",
        "    return gndrm_decode(id, buf);",
        "}",
        f"static const char *gndrm_ref(unsigned id) {{",
        f"    static _Thread_local char buf2[{MAX_MSG}];",
        "    return gndrm_decode(id, buf2);",
        "}",
        "static void gndrm_logfmt(const char *fmt, ...) {",
        "    va_list ap;",
        '    fputs("[gndrm-shim] ", stderr);',
        "    va_start(ap, fmt);",
        "    vfprintf(stderr, fmt, ap);",
        "    va_end(ap);",
        "}",
        "#define GNDRM_LOGM0(id) do { \\",
        '    if (getenv("GNDRM_LOG_SHIM")) gndrm_logfmt(gndrm_str(id)); \\',
        "} while (0)",
        "#define GNDRM_LOGM(id, ...) do { \\",
        '    if (getenv("GNDRM_LOG_SHIM")) gndrm_logfmt(gndrm_str(id), __VA_ARGS__); \\',
        "} while (0)",
        "/* --- end generated --- */",
    ]
    block = "\n".join(lines) + "\n"

    src, n = LOG_DEF.subn(block, src)
    if n != 1:
        raise SystemExit("obf-shim: LOG macro definition not found exactly once")

    open(out_path, "w").write(src)
    print(f"obf-shim: {len(msgs)} messages obfuscated -> {out_path}")


if __name__ == "__main__":
    main()
